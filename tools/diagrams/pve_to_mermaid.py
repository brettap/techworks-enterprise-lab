#!/usr/bin/env python3
"""
pve_to_mermaid.py - Techworks Enterprise Lab (SAM-ADM-003)
Author/Owner: Techworks

Reads the guests (VMs and containers) on each standalone Proxmox host with a
read-only API token and writes a Mermaid flowchart.

Nothing sensitive lives in this script or the repo:
  - Host addresses and token file paths come from an INI file outside the repo
    (default: ~/.config/techworks/pve-hosts.ini).
  - Token secrets are read from files outside the repo (chmod 600).
  - Anything that looks like an IPv4 address in the output is replaced with [ip].

Standard library only. Python 3.8+.

Usage:
  python3 tools/diagrams/pve_to_mermaid.py                       # prints Mermaid to the screen
  python3 tools/diagrams/pve_to_mermaid.py -o docs/diagrams/proxmox-guests.mmd
  python3 tools/diagrams/pve_to_mermaid.py --insecure            # self-signed TLS, lab test only
"""

import argparse
import configparser
import json
import os
import re
import ssl
import sys
import urllib.error
import urllib.request

DEFAULT_CONFIG = "~/.config/techworks/pve-hosts.ini"
DEFAULT_TOKEN_ID = "diagram@pve!diagram-script"
API_PATH = "/api2/json/cluster/resources?type=vm"
IPV4 = re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")


def scrub(text):
    """Replace anything that looks like an IPv4 address with a placeholder."""
    return IPV4.sub("[ip]", str(text))


def safe_id(text):
    """Mermaid node IDs: letters, digits and underscores only."""
    return re.sub(r"[^A-Za-z0-9_]", "_", text)


def label(text):
    """Mermaid label text: scrubbed, with double quotes swapped out."""
    return scrub(text).replace('"', "'")


def load_config(path):
    path = os.path.expanduser(path)
    if not os.path.isfile(path):
        sys.exit(f"Config file not found: {path}")
    cfg = configparser.ConfigParser()
    cfg.read(path)
    if not cfg.sections():
        sys.exit(f"No hosts found in {path}")
    return cfg


def read_secret(token_file):
    token_file = os.path.expanduser(token_file)
    with open(token_file, encoding="utf-8") as fh:
        secret = fh.read().strip()
    if len(secret) != 36:
        print(f"Warning: secret in {token_file} is {len(secret)} characters, expected 36.",
              file=sys.stderr)
    return secret


def tls_context(insecure, ca_file):
    if insecure:
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        return ctx
    if ca_file:
        return ssl.create_default_context(cafile=os.path.expanduser(ca_file))
    return ssl.create_default_context()


def fetch_guests(host, section, insecure, timeout):
    """Return a list of guest dicts for one host, or None if the call failed."""
    address = section.get("address")
    token_file = section.get("token_file")
    token_id = section.get("token_id", DEFAULT_TOKEN_ID)
    port = section.get("port", "8006")
    if not address or not token_file:
        print(f"[{host}] skipped: needs 'address' and 'token_file' in the config.", file=sys.stderr)
        return None

    secret = read_secret(token_file)
    req = urllib.request.Request(f"https://{address}:{port}{API_PATH}")
    req.add_header("Authorization", f"PVEAPIToken={token_id}={secret}")
    ctx = tls_context(insecure, section.get("ca_file"))

    try:
        with urllib.request.urlopen(req, context=ctx, timeout=timeout) as resp:
            body = json.load(resp)
    except urllib.error.HTTPError as err:
        print(f"[{host}] HTTP {err.code}: 401 = token or secret, 403 = permissions.", file=sys.stderr)
        return None
    except urllib.error.URLError as err:
        # Error text can contain the address, so scrub it.
        print(f"[{host}] could not connect: {scrub(err.reason)}", file=sys.stderr)
        return None

    guests = body.get("data", [])
    if not guests:
        print(f"[{host}] returned 0 guests. If that's wrong, check both permission rows "
              f"(user and token) on '/'.", file=sys.stderr)
    return guests


def render(results):
    """results: {host_name: [guest, ...] or None}. Returns Mermaid text."""
    lines = [
        "%% Generated by tools/diagrams/pve_to_mermaid.py - do not edit by hand.",
        "%% Addresses are replaced with placeholders.",
        "flowchart LR",
        "    classDef running fill:#d9f2d9,stroke:#2e7d32,color:#1b1b1b",
        "    classDef stopped fill:#eeeeee,stroke:#757575,color:#1b1b1b",
        "    classDef template fill:#e3ecfa,stroke:#1565c0,color:#1b1b1b,stroke-dasharray:4 3",
        "    classDef unreachable fill:#fdecea,stroke:#c62828,color:#1b1b1b",
    ]
    for host in sorted(results):
        guests = results[host]
        hid = safe_id(host)
        lines.append(f'    subgraph {hid}["{label(host)} (standalone)"]')
        if guests is None:
            lines.append(f'        {hid}_err["could not read this host"]:::unreachable')
        elif not guests:
            lines.append(f'        {hid}_none["no guests"]:::stopped')
        else:
            for g in sorted(guests, key=lambda x: x.get("vmid", 0)):
                vmid = g.get("vmid", "?")
                kind = "CT" if g.get("type") == "lxc" else "VM"
                name = g.get("name", f"{kind}-{vmid}")
                status = g.get("status", "unknown")
                tags = g.get("tags", "")
                text = f"{label(name)}<br/>{kind} {vmid} - {label(status)}"
                if tags:
                    text += f"<br/>tags: {label(tags.replace(';', ', '))}"
                if g.get("template") == 1:
                    css = "template"
                elif status == "running":
                    css = "running"
                else:
                    css = "stopped"
                lines.append(f'        {hid}_{safe_id(str(vmid))}["{text}"]:::{css}')
        lines.append("    end")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Proxmox guests to a Mermaid diagram.")
    parser.add_argument("-c", "--config", default=DEFAULT_CONFIG,
                        help=f"host list INI (default: {DEFAULT_CONFIG})")
    parser.add_argument("-o", "--output", help="write Mermaid to this file instead of the screen")
    parser.add_argument("--insecure", action="store_true",
                        help="skip TLS checks (self-signed lab certs; test use only)")
    parser.add_argument("--timeout", type=int, default=10, help="seconds per host (default 10)")
    args = parser.parse_args()

    cfg = load_config(args.config)
    results = {}
    for host in cfg.sections():
        results[host] = fetch_guests(host, cfg[host], args.insecure, args.timeout)
        count = "failed" if results[host] is None else f"{len(results[host])} guests"
        print(f"[{host}] {count}", file=sys.stderr)

    mermaid = render(results)
    if args.output:
        os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(mermaid)
        print(f"Wrote {args.output}", file=sys.stderr)
    else:
        print(mermaid, end="")

    # Exit code 1 if any host failed, so a CI job can catch it.
    return 1 if any(v is None for v in results.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
